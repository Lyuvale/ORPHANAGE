export default function Sidebar({
  children,
  navItems,
  centreName,
  isPlatformAdmin,
  isManager,
  unreadCount,
}: {
  children: React.ReactNode;
  navItems: NavItem[];
  centreName: string;
  isPlatformAdmin: boolean;
  isManager: boolean;
  unreadCount?: number;
}) {
  const pathname = usePathname();
  const [mobileOpen, setMobileOpen] = useState(false);

  return (
    <div className="flex h-screen bg-white">
      {mobileOpen && (
        <div
          className="fixed inset-0 z-40 bg-black/50 lg:hidden"
          onClick={() => setMobileOpen(false)}
        />
      )}

      {/* Sidebar — dark */}
      <aside
        className={`fixed inset-y-0 left-0 z-50 flex w-64 flex-col bg-zinc-950 transition-transform duration-200 ease-in-out lg:translate-x-0 ${
          mobileOpen ? "translate-x-0" : "-translate-x-full"
        }`}
      >
        {/* Brand */}
        <div className="flex h-14 items-center gap-3 border-b border-zinc-800 px-5">
          <div className="flex h-7 w-7 items-center justify-center rounded-md bg-white">
            <svg className="h-4 w-4 text-zinc-950" fill="none" viewBox="0 0 24 24" strokeWidth={2} stroke="currentColor">
              <path strokeLinecap="round" strokeLinejoin="round" d="M21 8.25c0-2.485-2.099-4.5-4.688-4.5-1.935 0-3.597 1.126-4.312 2.733-.715-1.607-2.377-2.733-4.313-2.733C5.1 3.75 3 5.765 3 8.25c0 7.22 9 12 9 12s9-4.78 9-12z" />
            </svg>
          </div>
          <div className="min-w-0">
            <p className="text-sm font-semibold text-white truncate">Care Platform</p>
            {isPlatformAdmin ? (
              <p className="text-[11px] font-medium text-zinc-400">Platform Admin</p>
            ) : centreName ? (
              <p className="text-[11px] font-medium text-zinc-400 truncate">{centreName}</p>
            ) : null}
          </div>
        </div>

        {/* Navigation */}
        <nav className="flex-1 overflow-y-auto px-3 py-3 space-y-0.5">
          {navItems.map((item) => {
            const isActive =
              pathname === item.href ||
              (item.href !== "/dashboard" && item.href !== "/admin" && pathname.startsWith(item.href));
            return (
              <Link
                key={item.href}
                href={item.href}
                onClick={() => setMobileOpen(false)}
                className={`flex items-center gap-3 rounded-md px-3 py-2 text-[13px] font-medium transition-colors ${
                  isActive
                    ? "bg-zinc-800 text-white"
                    : "text-zinc-300 hover:bg-zinc-900 hover:text-white"
                }`}
              >
                <span className={isActive ? "text-white" : "text-zinc-500"}>
                  {ICONS[item.icon] ?? ICONS.dashboard}
                </span>
                {item.label}
                {item.icon === "notifications" && unreadCount && unreadCount > 0 ? (
                  <span className="ml-auto inline-flex items-center justify-center rounded-full bg-white px-1.5 text-[10px] font-bold text-zinc-950">
                    {unreadCount > 9 ? "9+" : unreadCount}
                  </span>
                ) : null}
              </Link>
            );
          })}
        </nav>

        {/* Sign out */}
        <div className="border-t border-zinc-800 px-3 py-3">
          <SidebarSignOut />
        </div>
      </aside>

      {/* Main content */}
      <div className="flex-1 lg:pl-64">
        {/* Mobile top bar */}
        <div className="sticky top-0 z-30 flex h-14 items-center gap-3 border-b border-zinc-200 bg-white px-4 lg:hidden">
          <button
            type="button"
            onClick={() => setMobileOpen(true)}
            className="rounded-lg p-2 text-zinc-600 hover:bg-zinc-100"
          >
            <svg className="h-5 w-5" fill="none" viewBox="0 0 24 24" strokeWidth={1.5} stroke="currentColor">
              <path strokeLinecap="round" strokeLinejoin="round" d="M3.75 6.75h16.5M3.75 12h16.5m-16.5 5.25h16.5" />
            </svg>
          </button>
          <p className="text-sm font-semibold text-zinc-900">Care Platform</p>
        </div>
        <main className="p-6 lg:p-8">{children}</main>
      </div>
    </div>
  );
}

function SidebarSignOut() {
  const [loading, setLoading] = useState(false);

  async function handleSignOut() {
    setLoading(true);
    const { createClient } = await import("@/lib/supabase/client");
    const supabase = createClient();
    await supabase.auth.signOut();
    window.location.href = "/login";
  }

  return (
    <button
      onClick={handleSignOut}
      disabled={loading}
      className="flex w-full items-center gap-3 rounded-md px-3 py-2 text-[13px] font-medium text-zinc-400 hover:bg-zinc-900 hover:text-white transition-colors disabled:opacity-60"
    >
      <svg className="h-5 w-5" fill="none" viewBox="0 0 24 24" strokeWidth={1.5} stroke="currentColor">
        <path strokeLinecap="round" strokeLinejoin="round" d="M15.75 9V5.25A2.25 2.25 0 0013.5 3h-6a2.25 2.25 0 00-2.25 2.25v13.5A2.25 2.25 0 007.5 21h6a2.25 2.25 0 002.25-2.25V15m3 0l3-3m0 0l-3-3m3 3H9" />
      </svg>
      {loading ? "Signing out…" : "Sign out"}
    </button>
  );
}
